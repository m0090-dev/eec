const (
	// Windows batch script (for cmd.exe)
	// 1. プログラム未指定用：第一引数を --program にする
	// 引数が無い場合はそのタグのシェルを開く。
	windowsTagUtilsScript = `@echo off
chcp 65001 >nul
setlocal enabledelayedexpansion
%EECHOME_LINE%
if "%~1"=="" goto shell
set PROGRAM=%1
shift
set ARGS=
:loop
if "%~1"=="" goto run
if defined ARGS (set ARGS=!ARGS!,%~1) else (set ARGS=%~1)
shift
goto loop
:run
eec run --tag %TAGNAME% --program %PROGRAM% --program-args=!ARGS!
exit /b %ERRORLEVEL%
:shell
eec shell --tag %TAGNAME%
exit /b %ERRORLEVEL%
`

	// 2. プログラム指定済み用：全引数を --program-args にする
	windowsTagUtilsScriptProgramFixed = `@echo off
chcp 65001 >nul
setlocal enabledelayedexpansion
%EECHOME_LINE%
set ARGS=
:loop
if "%~1"=="" goto run
if defined ARGS (set ARGS=!ARGS!,%~1) else (set ARGS=%~1)
shift
goto loop
:run
eec run --tag %TAGNAME% --program-args=!ARGS!
exit /b %ERRORLEVEL%
`

	// PowerShell tag script (no fixed program). Arguments are passed
	// through as real argv elements; only the final hand-off to
	// --program-args joins them, CSV-escaping each argument so values
	// containing spaces or commas survive. With no arguments it
	// opens the tag's shell instead of erroring.
	powerShellTagUtilsScript = `# Generated by eec gen script for tag "%TAGNAME%"
%EECHOME_LINE%
function ConvertTo-CsvField([string]$s) {
    if ($s.Contains(',') -or $s.Contains('"')) {
        return '"' + $s.Replace('"', '""') + '"'
    }
    return $s
}
if ($args.Count -eq 0) {
    eec shell --tag %TAGNAME%
    exit $LASTEXITCODE
}
$program = [string]$args[0]
$rest = @()
if ($args.Count -gt 1) {
    $rest = @($args[1..($args.Count - 1)])
}
if ($rest.Count -gt 0) {
    $csv = ($rest | ForEach-Object { ConvertTo-CsvField ([string]$_) }) -join ','
    eec run --tag %TAGNAME% --program $program --program-args $csv
} else {
    eec run --tag %TAGNAME% --program $program
}
exit $LASTEXITCODE
`

	// PowerShell tag script (program fixed by the tag): all
	// arguments become --program-args, CSV-escaped like above.
	powerShellTagUtilsScriptProgramFixed = `# Generated by eec gen script for tag "%TAGNAME%"
%EECHOME_LINE%
function ConvertTo-CsvField([string]$s) {
    if ($s.Contains(',') -or $s.Contains('"')) {
        return '"' + $s.Replace('"', '""') + '"'
    }
    return $s
}
if ($args.Count -gt 0) {
    $csv = ($args | ForEach-Object { ConvertTo-CsvField ([string]$_) }) -join ','
    eec run --tag %TAGNAME% --program-args $csv
} else {
    eec run --tag %TAGNAME%
}
exit $LASTEXITCODE
`

	// POSIX sh tag script (no fixed program): the first argument is
	// the program, the remaining arguments are joined with commas and
	// passed via --program-args. Mirrors windowsTagUtilsScript.
	// With no arguments it opens the tag's shell.
	unixTagUtilsScript = `#!/bin/sh
# Generated by eec gen script for tag "%TAGNAME%"
%EECHOME_LINE%
if [ $# -eq 0 ]; then
    exec eec shell --tag %TAGNAME%
fi
PROGRAM="$1"
shift
ARGS=""
for a in "$@"; do
    if [ -n "$ARGS" ]; then
        ARGS="$ARGS,$a"
    else
        ARGS="$a"
    fi
done
if [ -n "$ARGS" ]; then
    exec eec run --tag %TAGNAME% --program "$PROGRAM" --program-args="$ARGS"
else
    exec eec run --tag %TAGNAME% --program "$PROGRAM"
fi
`

	// POSIX sh tag script (program fixed by the tag): all arguments
	// are joined with commas and passed via --program-args.
	// Mirrors windowsTagUtilsScriptProgramFixed.
	unixTagUtilsScriptProgramFixed = `#!/bin/sh
# Generated by eec gen script for tag "%TAGNAME%"
%EECHOME_LINE%
ARGS=""
for a in "$@"; do
    if [ -n "$ARGS" ]; then
        ARGS="$ARGS,$a"
    else
        ARGS="$a"
    fi
done
if [ -n "$ARGS" ]; then
    exec eec run --tag %TAGNAME% --program-args="$ARGS"
else
    exec eec run --tag %TAGNAME%
fi
`

	unixTagSimpleUtilsScript = ``
)

// fillTagScript substitutes the tag name and, when eecHome is
// non-empty, a shell-specific line that points EEC_HOME at the data
// directory the scripts were generated from (only when the caller
// has not already set it). eecHomeLine renders that line for one
// shell; an empty eecHome removes the placeholder line entirely.
func fillTagScript(template, tagName, eecHome string, eecHomeLine func(string) string) string {
	script := strings.ReplaceAll(template, "%TAGNAME%", tagName)
	if eecHome == "" {
		script = strings.ReplaceAll(script, "%EECHOME_LINE%\n", "")
		script = strings.ReplaceAll(script, "%EECHOME_LINE%", "")
	} else {
		script = strings.ReplaceAll(script, "%EECHOME_LINE%", eecHomeLine(eecHome))
	}
	return script
}

// cmdEecHomeLine renders the EEC_HOME line for batch scripts. In a
// batch file a literal % must be doubled.
func cmdEecHomeLine(dir string) string {
	return `if not defined EEC_HOME set "EEC_HOME=` + strings.ReplaceAll(dir, "%", "%%") + `"`
}

// psEecHomeLine renders the EEC_HOME line for PowerShell scripts,
// escaping the characters that are special inside a double-quoted
// PowerShell string.
func psEecHomeLine(dir string) string {
	r := strings.NewReplacer("`", "``", `"`, "`\"", "$", "`$")
	return `if (-not $env:EEC_HOME) { $env:EEC_HOME = "` + r.Replace(dir) + `" }`
}

// shEecHomeLines renders the EEC_HOME lines for POSIX sh scripts.
// The path sits inside a double-quoted ${...:=...} expansion, so it
// needs no word-splitting protection (spaces are fine); only the
// characters that stay special inside double quotes are escaped.
func shEecHomeLines(dir string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`")
	return ": \"${EEC_HOME:=" + r.Replace(dir) + "}\"\nexport EEC_HOME"
}

func toWindowsLineEndings(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n") // まずCRLFをLFに統一
	s = strings.ReplaceAll(s, "\r", "\n")   // 万一CRのみがあればLFに変換
	return strings.ReplaceAll(s, "\n", "\r\n")
}

func GenWindowsTagUtilsScript(tagName, eecHome string) string {
	script := fillTagScript(windowsTagUtilsScript, tagName, eecHome, cmdEecHomeLine)
	return toWindowsLineEndings(script)
}

func GenWindowsTagUtilsScriptProgramFixed(tagName, eecHome string) string {
	script := fillTagScript(windowsTagUtilsScriptProgramFixed, tagName, eecHome, cmdEecHomeLine)
	return toWindowsLineEndings(script)
}

func GenPowerShellTagUtilsScript(tagName, eecHome string) string {
	return fillTagScript(powerShellTagUtilsScript, tagName, eecHome, psEecHomeLine)
}

func GenPowerShellTagUtilsScriptProgramFixed(tagName, eecHome string) string {
	return fillTagScript(powerShellTagUtilsScriptProgramFixed, tagName, eecHome, psEecHomeLine)
}

func GenUnixTagUtilsScript(tagName, eecHome string) string {
	return fillTagScript(unixTagUtilsScript, tagName, eecHome, shEecHomeLines)
}

func GenUnixTagUtilsScriptProgramFixed(tagName, eecHome string) string {
	return fillTagScript(unixTagUtilsScriptProgramFixed, tagName, eecHome, shEecHomeLines)
}

func GenUnixSimpleTagUtilsScript(tagName string) string {
	return ""
}

func GenUtilsScript(rt interfaces.Runtime, outputDir string, clean bool) {
	tagDir := types.ResolveDataDir(rt)
	if tagDir == "" {
		return
	}
	scriptDir := outputDir
	if scriptDir == "" {
		scriptDir = filepath.Join(types.DEFAULT_SCRIPT_DIR, types.DEFAULT_UTILS_SCRIPT_DIR)
	}
	tagFileLists, _ := general.GetFilesWithExtension(tagDir, ".tag")
	tagNameLists := general.RemoveExtensions(general.BaseSlice(tagFileLists))
	rt.Logger().Debug().
		Str("tagNameLists", strings.Join(tagNameLists, ",")).Msg("")

	if clean {
		for _, name := range tagNameLists {
			baseName := "t" + name
			var extensions []string
			if rt.Env().GOOS() == "windows" {
				extensions = []string{".cmd", ".ps1"}
			} else {
				extensions = []string{".sh"}
			}
			for _, ext := range extensions {
				filePath := filepath.Join(scriptDir, general.AddExtension(baseName, ext))
				if err := rt.FS().Remove(filePath); err != nil {
					rt.Logger().Warn().Err(err).Str("file", filePath).Msg("Failed to remove script")
				}
			}
		}
		return
	}

	// When the tag store came from a portable source (EEC_HOME or an
	// exe-adjacent .eec), generated scripts embed that directory so
	// they resolve the same tags from any shell.
	eecHome := types.PortableDataDir(rt)

	for _, name := range tagNameLists {
		baseName := "t" + name
		rt.Logger().Debug().
			Str("tagName", name).Msg("")

		tagData, err := types.ReadTagData(rt, name)
		if err != nil {
			rt.Logger().Error().Err(err).Str("tag", name).Msg("Failed to read tag data")
			continue
		}

		configFile := tagData.ConfigFile
		var config types.Config
		if configFile != "" && general.FileExists(configFile) {
			config, err = types.ReadConfig(rt, configFile)
			if err != nil {
				rt.Logger().Error().Err(err).Str("configFile", configFile).Msg("Failed to read config file")
			}
		}

		hasProgram := tagData.Program != "" || config.Program.Path != ""

		// scripts accumulates every launcher variant for this tag:
		// .cmd + .ps1 on Windows, .sh elsewhere.
		type scriptFile struct {
			fileName string
			content  string
		}
		var scripts []scriptFile
		if rt.Env().GOOS() == "windows" {
			var cmdContent, psContent string
			if hasProgram {
				// すでにプログラムが決まっているなら、引数は全部 program-args へ
				cmdContent = GenWindowsTagUtilsScriptProgramFixed(name, eecHome)
				psContent = GenPowerShellTagUtilsScriptProgramFixed(name, eecHome)
			} else {
				// プログラムが決まっていないなら、1つ目をプログラムとして扱う
				cmdContent = GenWindowsTagUtilsScript(name, eecHome)
				psContent = GenPowerShellTagUtilsScript(name, eecHome)
			}
			scripts = []scriptFile{
				{general.AddExtension(baseName, ".cmd"), cmdContent},
				{general.AddExtension(baseName, ".ps1"), psContent},
			}
		} else {
			var content string
			if hasProgram {
				// すでにプログラムが決まっているなら、引数は全部 program-args へ
				content = GenUnixTagUtilsScriptProgramFixed(name, eecHome)
			} else {
				// プログラムが決まっていないなら、1つ目をプログラムとして扱う
				content = GenUnixTagUtilsScript(name, eecHome)
			}
			scripts = []scriptFile{
				{general.AddExtension(baseName, ".sh"), content},
			}
		}

		if err := rt.FS().MkdirAll(scriptDir, 0755); err != nil {
			rt.Logger().Error().Err(err).Msg("Failed to create utils script directory")
			return
		}

		for _, script := range scripts {
			tagUtilsScriptFile := filepath.Join(scriptDir, script.fileName)
			rt.Logger().Debug().
				Str("tagUtilsScriptContent", script.content).
				Str("tagUtilsScriptFileName", script.fileName).
				Msg("")

			file, err := rt.FS().Create(tagUtilsScriptFile)
			if err != nil {
				rt.Logger().Error().Err(err).Str("file", tagUtilsScriptFile).Msg("Failed to create file")
				return
			}

			func() {
				defer file.Close()
				_, err := file.WriteString(script.content)
				if err != nil {
					rt.Logger().Error().Err(err).Msg("Failed to write to file")
				}
			}()
		}
	}
}
